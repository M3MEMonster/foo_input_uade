;Known bugs: Loading the player, playing a sound and expunging the player 
;  causes a crash at the 3rd time playing

;The used MOVEP will be emulated by the 68060-library on 68060

;PLEASE COMMENT OUT UNUSED PARTS WITH "IFEQ 1, ENDC"


	INCDIR	asm-one:INCLUDE2.0/

	INCLUDE	MISC/DELIPLAYER.I
	INCLUDE LIBRARIES/DOS_LIB.I
	INCLUDE	LIBRARIES/DOS.I
	INCLUDE EXEC/EXEC_LIB.I
	INCLUDE	EXEC/MEMORY.I
	INCLUDE	GRAPHICS/GRAPHICS_LIB.I
	INCLUDE	GRAPHICS/GFXBASE.I
	INCLUDE INTUITION/INTUITION_LIB.I
	INCLUDE INTUITION/INTUITION.I
	INCLUDE	WORKBENCH/ICON_LIB.I
	INCLUDE	WORKBENCH/WORKBENCH.I
;	INCLUDE	OWN/CCRMAKRO
	include	'hardware/custom.i'

	INCDIR	ASM-ONE:OWN/POKEYNOISE/

DEBUG=0
DEBUG_SAP=0

	IFNE	DEBUG_SAP
RUN_SAP
	JSR	CHECK
	JSR	LOAD
	RTS
	ENDC

;HERE BEGIN DELIPLAYERHEADER

;2 fillwords due crashsafety on execute
BEGIN	MOVEQ.L	#-1,D0				; was $20
	RTS
;recognition delitracker
	DC.B	'DELIRIUM'
;pointer on tags
	DC.L	PLTAGARRAY
;versionstring
	DC.B	'$VER:POKEYNoise V0.25alpha',0
	EVEN

PLTAGARRAY
;name of player
	DC.L	DTP_PlayerName,PLAYERNAME
;my name :)
	DC.L	DTP_Creator,MYNAME
;modulerecognitionroutine, special version
	DC.L	DTP_Check2,CHECK
;load sound
	DC.L	DTP_InitPlayer,LOAD
;expunge module
	DC.L	DTP_EndPlayer,THROWOUT
;play routine
	DC.L	DTP_Interrupt,PLAY
;subsongarea
	DC.L	DTP_NewSubSongRange,SUBSONGAREA
;initialize sound
	DC.L	DTP_InitSound,INIT
;config player
	DC.L	DTP_Config,OPENWBLIB
;silence sound on stop
	DC.L	DTP_EndSound,SILENCEMOD
	DC.L	0

PLAYERNAME
	DC.B	'POKEYNoise V0.25alpha',0
	EVEN

;name of creator
MYNAME
	DC.B	'Achim Härtel',0
	EVEN

;to initialize the player open icon.library
OPENWBLIB
	LEA.L	WBNAME(PC),A1
	MOVEQ.L	#0,D0
	MOVE.L	4.W,A6
	JSR	_LVOOpenLibrary(A6)
	TST.L	D0
	BNE.S	.1
	MOVEQ.L	#-1,D0
	RTS

;if succeeded, write pointer into wbbase
.1	MOVE.L	D0,WBBASE
	MOVEQ.L	#0,D0
	RTS

WBNAME	DC.B	'icon.library',0
	EVEN

;base of icon.library
WBBASE	DC.L	0
;icon, which is used at loaded sound
ICONBASE	DC.L	0
;icon, which is used for check
ICONBASE2	DC.L	0

TYPESTR	DC.B	'TYPE',0
	EVEN
SONGSSTR	DC.B	'SONGS',0
	EVEN
POKEYSTR	DC.B	'POKEY',0
POKEYSTREND
	EVEN
AUDIOCORRECTSTR	DC.B	'AUDIOCORRECT',0
AUDIOCORRECTSTREND
	EVEN
RHSTR	DC.B	'RH',0
RHSTREND
	EVEN

PLAYERSTR	DC.B	'PLAYER',0
	EVEN

INITSTR	DC.B	'INIT',0
	EVEN

DEFSONGSTR	DC.B	'DEFSONG',0
	EVEN

MUSICSTR	DC.B	'MUSIC',0
	EVEN

INFONAMEBUF
	DS.B	200

SUBSONGAREA
PLAYSONG	DC.W	0
MINSONG	DC.W	0
MAXSONG	DC.W	0


VBI	DC.W	0
MUSIC	DC.W	-1	
	;for SAP-format
SNDFORMAT	DC.W	0	;0-POKEYNOISE, $FFFF-SAP_INIT, 1-SAP_M (B)
				;3-SAP_C
;AUDIOINTSTORE	DC.L	0
;to save userstack
USERSTK	DC.L	0

;check, if PN-module at all
CHECK
;.S	BRA.S	.S
	CLR.W	SNDFORMAT
;CHECK, IF SOUND BEGINS WITH $FF,$FF
	IFEQ	DEBUG_SAP
	MOVE.L	dtg_ChkData(A5),A0
	ENDC

	ifne	DEBUG_SAP
	MOVE.L	#$B0000,A0
	ENDC

	CMP.W	#$FFFF,(A0)
	BEQ.S	.CONT
	MOVE.L	(A0),D0
	LSR.L	#8,D0
	CMP.L	#'SAP',D0
	BEQ.S	.SAP
	MOVEQ.L	#-1,D0
	RTS

.SAP	MOVE.W	#-1,SNDFORMAT
	MOVEQ.L	#0,D0
	RTS

.CONT
;GET ICON WITH workbench.library
	TST.L	ICONBASE2
	BNE.S	.5
;get name of music together with path
	CLR.B	INFONAMEBUF
	MOVE.L	#INFONAMEBUF,dtg_PathArrayPtr(A5)
	MOVE.L	dtg_CopyDir(A5),A0
	JSR	(A0)
	MOVE.L	dtg_CopyFile(A5),A0
	JSR	(A0)
;get icon
	LEA.L	INFONAMEBUF(PC),A0
	MOVE.L	WBBASE(PC),A6
	JSR	_LVOGetDiskObject(A6)
	TST.L	D0
	BNE.S	.1
	MOVEQ.L	#-1,D0
	RTS

.1	MOVE.L	D0,ICONBASE2
;GET POINTER ON TYPE= WITH LVO_FINDTOOLTYPE
.5	MOVE.L	ICONBASE2(PC),A0
	MOVE.L	do_ToolTypes(A0),A0
	LEA.L	TYPESTR(PC),A1
	MOVE.L	WBBASE(PC),A6
	JSR	_LVOFindToolType(A6)
	TST.L	D0
	BNE.S	.2
.3
;if no TYPE= found, release icon structure
	MOVE.L	ICONBASE2(PC),A0
	MOVE.L	WBBASE(PC),A6
	JSR	_LVOFreeDiskObject(A6)
;clear iconbase2 (isnt valid anymore)
	CLR.L	ICONBASE2
	MOVEQ.L	#-1,D0			;RETURNCODE: FAILED
	RTS

.2
;CHECK FOR "POKEY"
	MOVE.L	D0,A0
	LEA.L	POKEYSTR(PC),A1
	MOVEQ.L	#POKEYSTREND-POKEYSTR-1,D0
.4	CMPM.B	(A0)+,(A1)+
	BNE.S	.3
	DBF	D0,.4	
;RELEASE ICON STRUCTURE
	MOVE.L	ICONBASE2(PC),A0
	MOVE.L	WBBASE(PC),A6
	JSR	_LVOFreeDiskObject(A6)
;clear iconbase2 (isnt valid anymore)
	CLR.L	ICONBASE2
	MOVEQ.L	#0,D0			;RETURNCODE: SUCCESS
	RTS

LOAD
	TST.W	SNDFORMAT
	BNE.S	.SKIPLOADICON

.PN
;.S	BRA.S	.S
;get name of sound together with path
	CLR.B	INFONAMEBUF
	MOVE.L	#INFONAMEBUF,dtg_PathArrayPtr(A5)
	MOVE.L	dtg_CopyDir(A5),A0
	JSR	(A0)
	MOVE.L	dtg_CopyFile(A5),A0
	JSR	(A0)
	LEA.L	INFONAMEBUF(PC),A0
;get icon belonging to the sound
	MOVE.L	WBBASE(PC),A6
	JSR	_LVOGetDiskObject(A6)
	TST.L	D0
	BNE.S	.I1
	MOVEQ.L	#-1,D0
	RTS

;store base of icon in ICONBASE
.I1	MOVE.L	D0,ICONBASE
.SKIPLOADICON
	IFEQ	DEBUG_SAP
;reserve 64-k-block 
	MOVE.L	4.W,A6
	MOVE.L	#$10000,D0
	MOVE.L	#MEMF_CLEAR,D1
	JSR	_LVOAllocMem(A6)
	TST.L	D0
	BNE.S	.2
	MOVEQ.L	#-1,D0			;RETURNCODE: FAILED
	RTS

;store base of 64k-block in AREA
.2
	ENDC
	ifne	DEBUG_SAP
	MOVE.L	#$c0000,d0
	ENDC

	MOVE.L	D0,AREA


;SORT SOUND FROM DELITRACKERFILEAREA TO EMUMEMORY (ATARI-FILE)
	MOVE.L	D0,A0
	IFEQ	DEBUG_SAP
	MOVE.L	dtg_ChkData(A5),A1
	MOVE.L	A1,A2
	ADD.L	dtg_ChkSize(A5),A2
	ENDC
	IFNE	DEBUG_SAP
	MOVE.L	#$B0000,A1
	MOVE.L	#$B0000+1830,A2
	ENDC

	TST.W	SNDFORMAT
	BEQ.S	.NOHEADERTEXT
	BRA.S	.SKIPHEADER2

.SKIPHEADER1				;SKIP SAP-HEADER
	ADDQ.L	#1,A1
.SKIPHEADER2
	CMP.L	A1,A2
	BLS.W	.FAIL
	CMP.B	#$FF,(A1)
	BNE.S	.SKIPHEADER1
	CMP.B	#$FF,1(A1)
	BNE.S	.SKIPHEADER1
	MOVE.L	A1,A3

.NOHEADERTEXT
.L4	CMP.B	#$FF,(A1)
	BNE.S	.L1
	CMP.B	#$FF,1(A1)
	BNE.S	.L1
;if segmentbegin ffff, omit it
	LEA.L	2(A1),A1

.L1	MOVEQ.L	#0,D0
	MOVEQ.L	#0,D1
;destination area begin is in d0
	MOVEP.W	1(A1),D0
	MOVE.B	(A1),D0
;destination area end is in d1 (inclusively)
	MOVEP.W	3(A1),D1
	MOVE.B	2(A1),D1
	LEA.L	4(A1),A1
;there are incomplete atari-segments at fileend too (shouldnt happen, but
;  what the hell)
;so if source data end, end resorting
.L2	CMP.L	A1,A2
	BLS.S	.L3
;else copy everytime one byte into destination emumem
	MOVE.B	(A1)+,(A0,D0.L)
;until end of segment isnt reached
	ADDQ.W	#1,D0
	CMP.W	D0,D1
	BHS.S	.L2
;end of segment: evaluate new segment
	BRA.S	.L4

.L3
	TST.W	SNDFORMAT
	BEQ.W	.PN_TOOLTYPES
					;SAP, END OF HEADER IS IN R_A3
	ST.B	AUDIOCORRECTRH
	IFEQ	DEBUG_SAP
	MOVE.L	dtg_ChkData(A5),A2
	ENDC
	IFNE	DEBUG_SAP
	MOVE.L	#$B0000,A2
	ENDC

	LEA.L	TYPESTR(PC),A1
	BSR.W	FINDSTR
	TST.L	D0
	BEQ.S	.SAPERR
	MOVE.L	D0,A0
	BSR.W	SKIPWHITESPACE
	MOVE.B	(A0),D0
	CMP.B	#'M',D0
	BEQ.S	.SAP_M
	CMP.B	#'B',D0
	BEQ.S	.SAP_B
	CMP.B	#'C',D0			;SAP-PLAY TYPE C DOESNT WORK YET
	BEQ.W	.SAP_C
					;SAP-FORMATS C,S,D,R NOT SUPPORTED

.FAIL
.SAPERR					;FREE MEMORY
	MOVE.L	AREA(PC),A1
	MOVE.L	#$10000,D0
	MOVE.L	4.W,A6
	JSR	_LVOFreeMem(A6)
	MOVEQ.L	#-1,D0
	RTS

.SAP_M
.SAP_B
	MOVE.W	#1,SNDFORMAT
	LEA.L	PLAYERSTR(PC),A1
	BSR.W	FINDSTR
	TST.L	D0
	BEQ.S	.SAPERR
	MOVE.L	D0,A0
	BSR.W	SKIPWHITESPACE
	BSR.W	CONV
	MOVE.W	D1,PLAYROUT
	ST	VBI

	LEA.L	INITSTR(PC),A1
	BSR.W	FINDSTR
	TST.L	D0
	BEQ.S	.SAPERR
	MOVE.L	D0,A0
	BSR.W	SKIPWHITESPACE
	BSR.W	CONV
	MOVE.W	D1,INITROUT

.SAP_MBC
	CLR.W	MINSONG
	CLR.W	PLAYSONG
	CLR.W	MAXSONG

	LEA.L	SONGSSTR(PC),A1
	BSR.W	FINDSTR
	TST.L	D0
	BEQ.S	.MSSK
	MOVE.L	D0,A0
	BSR.W	SKIPWHITESPACE
	BSR.W	CONV
	SUBQ.L	#1,D1
	MOVE.W	D1,MAXSONG
.MSSK

	LEA.L	DEFSONGSTR(PC),A1
	BSR.W	FINDSTR
	TST.L	D0
	BEQ.W	.DSSK
	MOVE.L	D0,A0
	BSR.W	SKIPWHITESPACE
	BSR.W	CONV
	MOVE.W	D1,PLAYSONG
.DSSK
	BRA.W	.FINISHLOAD

.SAP_C	MOVE.W	#$3,SNDFORMAT
	LEA.L	PLAYERSTR(PC),A1
	BSR.W	FINDSTR
	TST.L	D0
	BEQ.W	.SAPERR
	MOVE.L	D0,A0
	BSR.W	SKIPWHITESPACE
	BSR.W	CONV
	ADDQ.L	#3,D1
	MOVE.W	D1,INITROUT
	ADDQ.L	#3,D1
	MOVE.W	D1,PLAYROUT
	ST	VBI

	MOVE.W	#-1,MUSIC
	LEA.L	MUSICSTR(PC),A1
	BSR.W	FINDSTR
	TST.L	D0
	BEQ.W	.SAPERR
	MOVE.L	D0,A0
	BSR.W	SKIPWHITESPACE
	BSR.W	CONV
	MOVE.W	D1,MUSIC

	BRA.W	.SAP_MBC

.PN_TOOLTYPES
;in $02e0(atari) is soundinitroutine
	MOVE.W	#$02E0,D0
	MOVE.B	1(A0,D0.W),INITROUT
	MOVE.B	(A0,D0.W),INITROUT+1

	MOVE.L	ICONBASE(PC),A4
	MOVE.L	do_ToolTypes(A4),A4

;not implemented:
;GET AUTHOR
;GET COMPANY
;GET NAME

;GET MAXSONG, PLAYSONG, MINSONG
;SOURCE: MAX,PLAY,MINSONG
;DESTINATION: PLAY,MIN,MAXSONG WORD
	CLR.W	PLAYSONG
	CLR.W	MINSONG
	CLR.W	MAXSONG
;find SONG=
	MOVE.L	A4,A0
	LEA.L	SONGSSTR(PC),A1
	MOVE.L	WBBASE(PC),A6
	JSR	_LVOFindToolType(A6)
	TST.L	D0
	BEQ.S	.S1
;get max, play, minsong from icon
	MOVE.L	D0,A0
	BSR.S	CONV
	SUBQ.B	#1,D1
	MOVE.W	D1,MAXSONG
	TST.B	D0
	BEQ.S	.S1
	BSR.S	CONV
	SUBQ.B	#1,D1
	MOVE.W	D1,PLAYSONG
	TST.B	D0
	BEQ.S	.S1
	BSR.S	CONV
	SUBQ.B	#1,D1
	MOVE.W	D1,MINSONG

.S1
;get tooltype AUDIOCORRECTRH for rob hubbard-songs
	CLR.B	AUDIOCORRECTRH
	MOVE.L	A4,A0
	LEA.L	AUDIOCORRECTSTR(PC),A1
	MOVE.L	WBBASE(PC),A6
	JSR	_LVOFindToolType(A6)
	TST.L	D0
	BEQ.S	.S5
	MOVE.L	D0,A0
	LEA.L	RHSTR(PC),A1
	MOVEQ.L	#RHSTREND-RHSTR-1,D0
.S4	CMPM.B	(A0)+,(A1)+
	BNE.S	.S5
	DBF	D0,.S4
	ST.B	AUDIOCORRECTRH

.S5
;GET CUSTOM VBI (not implemented)
	CLR.W	VBI

;GET PLAYING TIMES (not implemented)


.FINISHLOAD
;	MOVEQ.L	#7,D0
;	LEA.L	AUDIOINTNODE,A1
;	MOVE.L	$4,A6
;	JSR	_LVOSETINTVECTOR(A6)
;	MOVE.L	D0,AUDIOINTSTORE
;	MOVE.L	D0,$100

;	MOVE.L	$70.W,AUDIOINTSTORE
;	MOVE.L	#INT4,$70.W
;ALLOC AUDIOCHANNELS
	IFEQ	DEBUG_SAP
	MOVE.L	dtg_AudioAlloc(A5),A0
	JSR	(A0)
	ENDC
	MOVEQ.L	#0,D0
	RTS

;converts hexnumber-ascii in hex, maximum: longword
CONV	MOVEQ.L	#0,D1
;number ends at , or NULL OR $A OR $D
.S1	MOVE.B	(A0)+,D0
	CMP.B	#',',D0
	BEQ.S	.S3
	CMP.B	#$0,D0
	BEQ.S	.S3
	CMP.B	#$A,D0
	BEQ.S	.S3
	CMP.B	#$D,D0
	BEQ.S	.S3
	SUB.B	#$30,D0
	CMP.B	#$31,D0
	BLO.S   .S4
	SUB.W   #$27,D0
	BRA.S   .S2
.S4	CMP.B	#$11,D0
	BLO.S	.S2
	SUBQ.W	#7,D0
.S2	LSL.L	#4,D1
	OR.B	D0,D1
	BRA.S	.S1

.S3	RTS

;FINDS THE VALUE OF A KEYWORD
;INPUT:
;A1-STRING TO SEARCH (KEYWORD)
;A2-BEGIN OF STRING TO SEARCH IN
;A3-END OF STRING TO SEARCH IN
;RETURNS:
;D0- RETURNCODE: 0 FAILED, ELSE ADDRESS OF VALUE OF THE STRING-KEYWORD
FINDSTR
	MOVE.L	A1,D0
	MOVE.L	A2,A0
;	BRA.S	.F3

.F2
;	ADDQ.L	#1,A0
.F3	MOVE.L	D0,A1		;PUT BEGIN OF KEYWORD IN SCRATCHREGISTER

.F1	CMP.L	A0,A3
	BLS.S	.FAIL
	CMPM.B	(A1)+,(A0)+
	BNE.S	.F2
;	ADDQ.L	#1,A0
;	ADDQ.L	#1,A1
	TST.B	(A1)
	BNE.S	.F1
				;SUCCESS	
	MOVE.L	A0,D0
	RTS

.FAIL	MOVEQ.L	#0,D0
	RTS



;SKIPS WHITESPACE
;A0-STRINGADDRESS
SKIPWHITESPACE
	BRA.S	.1

.2	ADDQ.L	#1,A0
.1	MOVE.B	(A0),D0
	CMP.B	#$9,D0
	BEQ.S	.2
	CMP.B	#$20,D0
	BEQ.S	.2
	RTS

;ends module
THROWOUT
;release 64k-block
	MOVE.L	AREA(PC),A1
	MOVE.L	#$10000,D0
	MOVE.L	4.W,A6
	JSR	_LVOFreeMem(A6)

;RELEASE ICON STRUCTURE
	TST.L	ICONBASE
	BEQ.S	.SKIB
	MOVE.L	ICONBASE(PC),A0
	MOVE.L	WBBASE(PC),A6
	JSR	_LVOFreeDiskObject(A6)
	CLR.L	ICONBASE
.SKIB
;	MOVE.L	AUDIOINTSTORE,$70.W

;	MOVE.L	AUDIOINTSTORE,A1
;	MOVEQ.L	#7,D0
;	MOVE.L	$4,A6
;	JSR	_LVOSETINTVECTOR(A6)
;deallocate audiochannels
	IFEQ	DEBUG_SAP	
	MOVE.L	dtg_AudioFree(A5),A0
	JSR	(A0)
	ENDC

	MOVEQ.L	#0,D0
	RTS

SILENCEMOD
;silence all sound channels
	MOVE.L	#SILENCE,$DFF0A0
	MOVE.W	#4,$DFF0A4
	MOVE.W	#$100,$DFF0A6
	MOVE.L	#0,$DFF0A8
	MOVE.L	#SILENCE,$DFF0B0
	MOVE.W	#4,$DFF0B4
	MOVE.W	#$100,$DFF0B6
	MOVE.L	#0,$DFF0B8
	MOVE.L	#SILENCE,$DFF0C0
	MOVE.W	#4,$DFF0C4
	MOVE.W	#$100,$DFF0C6
	MOVE.L	#0,$DFF0C8
	MOVE.L	#SILENCE,$DFF0D0
	MOVE.W	#4,$DFF0D4
	MOVE.W	#$100,$DFF0D6
	MOVE.L	#0,$DFF0D8
	RTS

INIT
;.S	BRA.S	.S
;due 6502-emulation switch into supervisormode (the old ccr-problem)
	MOVE.L	4.W,A6
	JSR	_LVOSuperState(A6)
;rescue stack
	MOVE.L	D0,USERSTK

	MOVE.W	SNDFORMAT(PC),D0
	CMP.W	#3,D0			;SAP TYPE C
	BNE.S	.INITALL
	
	MOVE.L	AREA(PC),A4
;put 6502-pc on soundinitroutine
	MOVE.W	INITROUT(PC),PCSTORE
;load 6502-a with init: $70
	MOVEQ.L	#$70,D3
;6502-x,y: musicaddress
	MOVEQ.L	#0,D4
	MOVEQ.L	#0,D5
	MOVE.B	MUSIC+1(PC),D4
	MOVE.B	MUSIC(PC),D5
;execute 6502-soundinitroutine
	BSR.W	EMU
	TST.L	D0
	BNE.S	.INITERR
;put 6502-pc on soundinitroutine
	MOVE.W	INITROUT(PC),PCSTORE
;load 6502-a with init2:
	MOVEQ.L	#$0,D3
;6502-x musicnumber
	MOVEQ.L	#0,D4
	IFEQ	DEBUG_SAP
	MOVE.W	dtg_SndNum(A5),D4
	ENDC
;clear 6502-y
	MOVEQ.L	#0,D5
;execute 6502-soundinitroutine
	BSR.W	EMU
	TST.L	D0
	BNE.S	.INITERR
	BRA.S	.2

.INITALL
	MOVE.L	AREA(PC),A4
;put 6502-pc on soundinitroutine
	MOVE.W	INITROUT(PC),PCSTORE
	MOVEQ.L	#0,D3
;load 6502-a with soundnumber
	IFEQ	DEBUG_SAP
	MOVE.W	dtg_SndNum(A5),D3
	ENDC
;clear 6502-x,y
	MOVEQ.L	#0,D4
	MOVEQ.L	#0,D5
;execute 6502-soundinitroutine
	BSR.W	EMU
	TST.L	D0
	BEQ.S	.2
;emulation failed on sound init (illegal instruction)
.INITERR
;switch back into user mode
	MOVE.L	USERSTK(PC),D0
	MOVE.L	4.W,A6
	JSR	_LVOUserState(A6)
;	MOVE.W	#$820F,$DFF096
	MOVEQ.L	#-1,D0			;RETURNCODE: FAILED
	RTS

;vbi set explicitely? (only implemented in sap)
.2	TST.W	VBI
	BNE.S	.1
;no, get from $222(atari) and put in PLAYROUT
	MOVE.B	$222(A4),PLAYROUT+1
	MOVE.B	$223(A4),PLAYROUT
.1
;clear the time the subsong already played
	CLR.L	TIMER
;RESET CHANNELSAMPLES
	MOVE.L	#SILENCE,D0
	MOVE.L	D0,CH0SMPL
	MOVE.L	D0,CH1SMPL
	MOVE.L	D0,CH2SMPL
	MOVE.L	D0,CH3SMPL
	MOVEQ.L	#4,D0
